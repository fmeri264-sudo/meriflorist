export function getDistrict(slug: string): District | undefined {
  return DISTRICTS.find(d => d.slug === slug)
}

export function getOtherDistricts(slug: string): District[] {
  return DISTRICTS.filter(d => d.slug !== slug)
}

const SB = process.env.SUPABASE_URL!
const KEY = process.env.SUPABASE_ANON_KEY!
const SB_HEADERS = { apikey: KEY, Authorization: `Bearer ${KEY}` }

export async function getDistrictData(slug: string): Promise<District | undefined> {
  try {
    const res = await fetch(
      `${SB}/rest/v1/Districts?slug=eq.${encodeURIComponent(slug)}&select=data&limit=1`,
      { headers: SB_HEADERS, cache: 'no-store' },
    )
    if (res.ok) {
      const rows: { data: District }[] = await res.json()
      if (rows.length > 0) return rows[0].data
    }
  } catch { /* ignore, use fallback */ }
  return DISTRICTS.find(d => d.slug === slug)
}

export async function saveDistrictData(slug: string, data: District): Promise<void> {
  await fetch(`${SB}/rest/v1/Districts`, {
    method: 'POST',
    headers: {
      ...SB_HEADERS,
      'Content-Type': 'application/json',
      Prefer: 'resolution=merge-duplicates',
    },
    body: JSON.stringify({ slug, data }),
  })
}
